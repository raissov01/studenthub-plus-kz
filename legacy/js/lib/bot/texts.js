// '2026-12-07' -> '7 желтоқсан' / '7 декабря'; the year is added only when it is not the current one.
export function fmtDate(iso, lang, today) {
  const [y, m, d] = iso.split('-').map(Number);
  const base = `${d} ${MONTHS[lang][m - 1]}`;
  return today && String(y) !== today.slice(0, 4) ? `${base} ${y}` : base;
}

const ruDays = n => {
  const a = n % 10, b = n % 100;
  if (a === 1 && b !== 11) return 'день';
  if (a >= 2 && a <= 4 && (b < 12 || b > 14)) return 'дня';
  return 'дней';
};

const joinKk = list => (list.length < 2 ? list.join('') : `${list.slice(0, -1).join(', ')} және ${list.at(-1)}`);
const joinRu = list => (list.length < 2 ? list.join('') : `${list.slice(0, -1).join(', ')} и ${list.at(-1)}`);

