import { test, expect, label, response, approve } from './helpers';

test('11-013: company verification → job moderation → application → invite → student notice', async ({ actor, lang }) => {
  const employer = await actor(`Employer ${lang}`);
  const student = await actor(`Applicant ${lang}`);
  const admin = await actor(`Employer admin ${lang}`, { admin: true });
  const p = employer.page;
  const company = `Campus company ${lang}`;
  await p.goto('/employer/apply');
  await p.locator('#eaName').fill(company);
  await p.locator('#eaBin').fill(lang === 'kk' ? '123456789012' : '123456789013');
  await p.locator('#eaSite').fill('https://example.org/company');
  await p.locator('#eaContact').fill(employer.name);
  await response(p, '/api/employer/apply', () => p.getByRole('button', { name: label(lang, 'Тексеруге жіберу', 'Отправить на проверку'), exact: true }).click());
  await approve(admin.page, lang, company);
  await p.goto('/employer/jobs/new');
  await p.getByRole('checkbox').check();
  await response(p, '/api/employer/rules/accept', () => p.getByRole('button', { name: label(lang, 'Жалғастыру', 'Продолжить'), exact: true }).click());
  const title = `Campus assistant ${lang}`;
  const fields = { titleKk: title, titleRu: title, descKk: 'Help students find books and organise the campus library.', pay: '10000', hours: '4', schedKk: 'Saturday afternoon', address: 'Campus library', applyKk: 'Apply through Student Hub' };
  for (const [id, value] of Object.entries(fields)) await p.locator(`#jf_${id}`).fill(value);
  await p.getByRole('radio', { name: label(lang, 'Иә, сай', 'Да, подходит'), exact: true }).check();
  const created = await response(p, '/api/employer/jobs', () => p.getByRole('button', { name: label(lang, 'Жариялау', 'Опубликовать'), exact: true }).click());
  const id = created.job.id;
  expect(created.job.status).toBe('pending');
  await approve(admin.page, lang, title);
  await student.page.goto(`/job/job-${id}`);
  await expect(student.page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await student.page.getByRole('button', { name: label(lang, 'Өтінім жіберу', 'Откликнуться'), exact: true }).click();
  const dialog = student.page.getByRole('dialog');
  await dialog.getByRole('checkbox', { name: new RegExp(`^${label(lang, 'Аты', 'Имя')}`) }).check();
  await dialog.getByRole('button', { name: label(lang, 'Жалғастыру', 'Далее'), exact: true }).click();
  await response(student.page, `/api/jobs/${id}/apply`, () => dialog.getByRole('button', { name: label(lang, 'Жіберу', 'Отправить'), exact: true }).click());
  const applications = await (await student.page.request.get('/api/applications/my')).json();
  const application = applications.applications.find((a: { jobId: string }) => a.jobId === `job-${id}`);
  expect(application.status).toBe('sent');
  await p.goto(`/employer/jobs/${id}`);
  const card = p.locator('.card').filter({ hasText: student.name });
  await card.getByRole('button', { name: label(lang, 'Шақыру', 'Пригласить'), exact: true }).click();
  const message = `Interview at campus library at 14:00 ${lang}`;
  await p.getByRole('dialog').locator('textarea').fill(message);
  await response(p, `/api/employer/applications/${application.id}/status`, () => p.getByRole('dialog').getByRole('button', { name: label(lang, 'Шақыру', 'Пригласить'), exact: true }).click());
  await student.page.goto('/mine');
  await expect(student.page.getByText(message, { exact: false })).toBeVisible();
  await student.page.goto('/notifications');
  await expect(student.page.getByText(new RegExp(message))).toBeVisible();
  const inbox = await (await student.page.request.get('/api/me/inbox')).json();
  expect(JSON.stringify(inbox)).toContain(message);
  expect(JSON.stringify(inbox)).toContain(company);
});
