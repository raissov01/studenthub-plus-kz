/** the /admin/* screens (inside AdminLayout) */
function adminScreen(prm: string) {
  if (!prm) return <Admin />;
  const sub = prm.replace(/\?.*$/, '');
  if (sub === 'users') return <AdminUsers />;
  if (sub === 'audit') return <AdminAudit />;
  if (sub === 'roles') return <AdminRoles />;
  if (sub === 'exports') return <AdminExports />;
  if (sub === 'voice') return <AdminVoice />;
  if (sub === 'moderation') return <AdminModeration />;
  if (sub === 'shop') return <AdminShop />;
  if (sub === 'schedule') return <AdminSchedule />;
  if (sub === 'attendance') return <AdminAttendance />;
  if (sub === 'payments') return <AdminPayments />;
  if (sub === 'settings') return <AdminSettings />;
  if (prm === 'health') return <AdminHealth />;
  if (prm === 'queue') return <AdminQueue />;
  if (prm === 'reports') return <AdminReports />;
  if (prm === 'mentors') return <AdminMentors />;
  if (prm === 'ambassadors') return <AdminAmbassadors />;
  if (prm === 'market') return <AdminMarket />;
  if (prm === 'employers') return <AdminEmployers />;
  if (prm === 'staff') return <AdminStaff />;
  if (prm === 'points') return <AdminPoints />;
  if (prm === 'cafe' || prm.startsWith('cafe?')) return <AdminCafe />;
  if (prm === 'print' || prm.startsWith('print?')) return <AdminPrint />;
  if (prm === 'clubs') return <AdminClubs />;
  if (prm === 'feeds') return <AdminFeeds />;
  if (prm === 'content' || prm.startsWith('content/') || prm.startsWith('content?')) return <AdminContent prm={prm} />;
  return <NotFound />;
}

export function Screen({ v }: { v: string }) {
  const [name, prm] = parseView(v);
  switch (name) {
    case 'search': return <Search />;
    case 'notif': return <Notifications />;
    case 'profile': return <Profile />;
    case 'services': return <Services />;
    case 'materials': return <Materials />;
    case 'saved': return <Saved />;
    // the sections (/jobs, /internships, /events, /courses, /discounts), each with its own sub-tabs
    case 'opps': case 'bonus': { const sec = sectionOfView(name, prm) ?? 'jobs'; return <SectionScreen key={sec} section={sec} />; }
    case 'mine': return <Mine />;
    case 'job': return <JobView id={prm} />;
    case 'opp': return <OppView id={prm} />;
    case 'event': return /^\d+$/.test(prm) ? <DbEventView id={prm} /> : <NotFound />;
    case 'ai': return <Ai />;
    case 'chat': return <Chat />;
    case 'resume': return <Resume />;
    case 'interview': return <Interview />;
    case 'exam': return <Exam />;
    case 'plan': return <PlanView id={prm} />;
    case 'cards': return <Cards />;
    case 'deck': return <DeckView id={prm} />;
    case 'study': return <Study />;
    case 'match': return <Match id={prm || undefined} />;
    case 'edit': return <Edit />;
    case 'gpa': return <Gpa />;
    case 'docs': return <Docs />;
    case 'doc': return <DocView id={prm} />;
    case 'admission': return <Admission />;
    case 'map': return <MapView tab={prm === 'near' ? 'near' : 'campus'} />;
    case 'pay': return <Pay />;
    case 'portfolio': return <Portfolio />;
    case 'settings': return <Settings />;
    case 'roadmap': return <Roadmap />;
    case 'privacy': return <Privacy />;
    case 'admin': return <AdminLayout view={v}>{adminScreen(prm)}</AdminLayout>;
    case 'ambassador': return prm === 'mentors' ? <AmbassadorMentors /> : <Ambassador prm={prm} />;
    case 'mentors': return <Mentors prm={prm} />;
    case 'market': return <Market prm={prm} />;
    case 'organize': return <Organize prm={prm} />;
    case 'checkin': return <Checkin />;
    case 'certificate': return prm ? <CertificateView code={prm} /> : <NotFound />;
    case 'employer': return <EmployerCabinet prm={prm} />;
    case 'university': return <UniversityCabinet />;
    case 'announcements': return <Announcements />;
    case 'suggest': return <SuggestPage />;
    case 'suggestions': return <MySuggestionsPage />;
    case 'calendar': return <CalendarView />;
    case 'points': return <Points />;
    case 'cafe': return <CafeScreen prm={prm} />;
    case 'print': return <PrintScreen prm={prm} />;
    case 'subjects': return <SubjectsScreen />;
    case 'timetable': return <TimetableScreen />;
    case 'notes': return <NotesScreen />;
    case 'review': return <ReviewScreen />;
    case 'surveys': return <SurveysScreen />;
    case 'feedback': return <FeedbackScreen />;
    case 'wellbeing': return <WellbeingScreen />;
    case 'voice': return <VoiceStaff />;
    case 'lostfound': return <LostFoundScreen />;
    case 'qa': return <QAScreen />;
    case 'roommates': return <RoommatesScreen />;
    case 'clubs': return <ClubsScreen />;
    case 'club': return <ClubScreen />;
    case 'grades': return <GradesScreen />;
    case 'applications': return <ApplicationsScreen />;
    case 'booth': return <BoothScreen />;
    default: return <Home />;
  }
}
