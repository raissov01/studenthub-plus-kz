package server

import (
	"fmt"
	"net/http"
	"sort"
	"strings"
)

// Route is an entry in the actual runtime router. Policy documents the reviewed handler
// semantics; it is deliberately explicit so a new route requires a security review.
type Route struct {
	Pattern string
	Handler http.Handler
	Policy  RoutePolicy
}
type RoutePolicy struct{ Callers, RateLimit, Validation, Feature string }
type collector struct {
	mux    *http.ServeMux
	routes []Route
}

func (c *collector) Handle(pattern string, h http.Handler) {
	c.mux.Handle(pattern, h) // retain ServeMux's duplicate/ambiguous route checks
	c.routes = append(c.routes, Route{Pattern: pattern, Handler: h, Policy: routePolicies[pattern]})
}
func (c *collector) HandleFunc(pattern string, h func(http.ResponseWriter, *http.Request)) {
	c.Handle(pattern, http.HandlerFunc(h))
}

// Inventory walks the same registrations used to construct Handler, including fallback.
func Inventory() []Route {
	c := &collector{mux: http.NewServeMux()}
	registerAll(c)
	sort.Slice(c.routes, func(i, j int) bool { return c.routes[i].Pattern < c.routes[j].Pattern })
	return c.routes
}

func SecurityDocument() (string, error) {
	var b strings.Builder
	b.WriteString(securityIntro)
	seen := map[string]bool{}
	for _, r := range Inventory() {
		p := r.Policy
		if p.Callers == "" || p.RateLimit == "" || p.Validation == "" || p.Feature == "" {
			return "", fmt.Errorf("missing security review: %s", r.Pattern)
		}
		method, path, ok := strings.Cut(r.Pattern, " ")
		if !ok {
			method, path = "ANY", r.Pattern
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s |\n", method, path, p.Callers, p.RateLimit, p.Validation, p.Feature)
		seen[r.Pattern] = true
	}
	for pattern := range routePolicies {
		if !seen[pattern] {
			return "", fmt.Errorf("obsolete security review: %s", pattern)
		}
	}
	return b.String(), nil
}

